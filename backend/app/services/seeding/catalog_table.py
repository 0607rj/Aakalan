"""The catalog as one plain table for people to read (`python -m app.cli catalog-table`).

A view only: it is generated from the catalog YAML and simple-mode config, and nothing reads it
back, so it never changes a price. Run the command again after the catalog changes."""

from collections import defaultdict
from dataclasses import dataclass
from decimal import Decimal
from itertools import groupby
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font
from openpyxl.utils import get_column_letter

from app.services.engine.reference import Catalog, Size
from app.services.quick.config import QuickConfig

HEADERS = [
    "Section",
    "Block",
    "What it includes",
    "Small (days)",
    "Medium (days)",
    "Large (days)",
    "Used by",
    "Work split",
    "Grows with",
    "Confidence",
    "Key",
]


@dataclass
class Row:
    section: str
    name: str
    description: str
    small: Decimal | None
    medium: Decimal | None
    large: Decimal | None
    used_by: str
    work_split: str
    grows_with: str
    confidence: str
    key: str

    def cells(self) -> list[str | float | None]:
        days = [float(d) if d is not None else None for d in (self.small, self.medium, self.large)]
        return [
            self.section,
            self.name,
            self.description,
            *days,
            self.used_by,
            self.work_split,
            self.grows_with,
            self.confidence,
            self.key,
        ]


def used_by(cfg: QuickConfig) -> dict[str, list[str]]:
    """Which form choices bring each block into a project: features, scope items, the standard
    blocks of a project size, extra-feature types and answers that add a block."""
    uses: dict[str, list[str]] = defaultdict(list)
    for tier in cfg.sizing.tiers:
        for key in tier.base_components:
            note = "Standard block"
            if note not in uses[key]:
                uses[key].append(note)
    for f in cfg.features:
        for key in f.components:
            uses[key].append(f"Feature: {f.label}")
    for group in cfg.scope:
        for item in group.items:
            for key in item.adds:
                uses[key].append(f"Scope: {item.label}")
    for t in cfg.custom_feature_types.values():
        uses[t.component].append(f"Extra feature: {t.label}")
    for q in cfg.questions.values():
        for option in q.options:
            for key in option.extra_components:
                uses[key].append(f"Answer: {q.label} {option.label}")
    return uses


def rows(catalog: Catalog, cfg: QuickConfig) -> list[Row]:
    """One row per catalog block, in section order, then the catalog's order."""
    uses = used_by(cfg)
    order = {key: n for n, key in enumerate(catalog.sections)}
    out = []
    # sorted() keeps the catalog's order within a section
    for c in sorted(catalog.components, key=lambda c: order.get(c.section or "", len(order))):
        effort = c.base_effort_pd
        split = sorted(c.task_mix.items(), key=lambda kv: -kv[1])
        out.append(
            Row(
                section=catalog.sections.get(c.section or "", c.section or ""),
                name=c.name,
                description=c.description,
                small=effort.get(Size.S),
                medium=effort.get(Size.M),
                large=effort.get(Size.L),
                used_by="; ".join(uses.get(c.key, [])) or "Not used by the form",
                work_split=", ".join(f"{task} {share * 100:.0f}%" for task, share in split),
                grows_with=", ".join(c.applicable_drivers),
                confidence=c.confidence or "",
                key=c.key,
            )
        )
    return out


def _days(d: Decimal | None) -> str:
    return "" if d is None else f"{d.normalize():f}"


def _cell(text: str) -> str:
    return text.replace("|", "/").replace("\n", " ")


def write_markdown(catalog: Catalog, table: list[Row], path: Path) -> None:
    lines = [
        f"# Catalog v{catalog.version.lstrip('v')} in plain words",
        "",
        "Generated by `cd backend && uv run python -m app.cli catalog-table`; do not edit by hand.",
        "The engine prices from `backend/seeds/catalog/` and `backend/seeds/quick_estimate.yaml`,",
        "never from this page.",
        "",
        "- **Small / Medium / Large** are the block's person-days when the feature is Basic /",
        "  Standard / Advanced on the form. The price adjusts them further for the project",
        "  (calibration, languages, security level, AI tools, building on a CMS ...), then",
        "  multiplies by each role's day rate from the rate card.",
        "- **Used by**: which form choices bring the block in. A *standard block* is part of",
        "  every project of its size.",
        "- **Work split**: how the days divide between kinds of work, each paid at its",
        "  role's rate.",
        "- **Grows with**: answers that add effort to this block.",
        "",
    ]
    for section, group in groupby(table, key=lambda r: r.section):
        lines += [
            f"## {section}",
            "",
            "| Block | What it includes | Small | Medium | Large | Used by |",
            "|---|---|---|---|---|---|",
        ]
        lines += [
            f"| {_cell(r.name)} | {_cell(r.description)} | {_days(r.small)} | "
            f"{_days(r.medium)} | {_days(r.large)} | {_cell(r.used_by)} |"
            for r in group
        ]
        lines.append("")
    path.write_bytes("\n".join(lines).encode("utf-8"))


def write_excel(catalog: Catalog, table: list[Row], path: Path) -> None:
    book = Workbook()
    sheet = book.active
    assert sheet is not None
    sheet.title = f"Catalog {catalog.version}"
    sheet.append(HEADERS)
    for cell in sheet[1]:
        cell.font = Font(bold=True)
    for r in table:
        sheet.append(r.cells())
    widths = [28, 34, 60, 10, 10, 10, 50, 50, 24, 12, 30]
    for index, width in enumerate(widths, start=1):
        sheet.column_dimensions[get_column_letter(index)].width = width
    for line in sheet.iter_rows(min_row=2):
        for cell in line:
            cell.alignment = Alignment(wrap_text=True, vertical="top")
    sheet.freeze_panes = "C2"
    sheet.auto_filter.ref = sheet.dimensions
    path.parent.mkdir(parents=True, exist_ok=True)
    book.save(path)
